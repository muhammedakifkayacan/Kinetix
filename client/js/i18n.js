  function getLangPack(lang) {
    return TRANSLATIONS[lang] || TRANSLATIONS.tr;
  }

  function format(template, vars) {
    var out = template || '';
    if (!vars) return out;
    Object.keys(vars).forEach(function (k) {
      out = out.replace(new RegExp('\\{' + k + '\\}', 'g'), String(vars[k]));
    });
    return out;
  }

